"""One-off targeted fix, 2026-08-19: items 73, 582 (Asserção-Razão) and
439, 510 (Múltipla Escolha Complexa) were regenerated by gpt-oss-20b during
the qwen remediation pass with a generic, topic-free stem template
identical across items of the same format ("Ao analisar as asserções,
assinale a alternativa correta." / "Ao analisar o contexto apresentado, é
correto APENAS o que se afirma em:") -- unlike the original Phi-4
generations, which always wove the specific topic into the stem. This
surfaced as two spurious similarity=1.0000 pairs in the R41 diversity
re-check (false positives for true duplication -- the actual
assertions/statements/options differ completely -- but a real, minor
model-specific stylistic regression worth fixing and logging).

Re-generates just these 4 items from the ORIGINAL dataset row (never from
the flawed regenerated text), with an explicit extra instruction seeded
into the feedback channel on EVERY attempt (not just after a rejection):
the stem must name the item's specific topic, not a generic template.
Reuses generator_agent()/apply_position_shuffle()/run_mechanical_prefilter()
/judge_agent() directly -- the same per-attempt loop process_item() runs,
just with the instruction always present since process_item() itself has
no hook for seeding feedback before the first attempt.

Updates output/entregavel_2_100_questoes_qwen_validated.csv in place
(only these 4 rows), and appends to output/aig_audit_trail_qwen_remediation.jsonl.
"""
import asyncio
import json
import random
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, "/home/CIN/vflc/meu_projeto_mestrado")
from WAPLA_AIG_Engine import (  # noqa: E402
    SEED, apply_position_shuffle, build_candidate_pool, describe_word_count_violations,
    determine_target_level, generator_agent, item_to_row, judge_agent,
    run_mechanical_prefilter,
)

GENERATOR_MODEL = "vllm_local/gpt-oss-20b@8000"
JUDGE_MODEL = "vllm_local/qwen3.6-27b@8001"
MAX_RETRIES = 4
CSV_PATH = Path("output/entregavel_2_100_questoes_qwen_validated.csv")

TARGET_QIDS = [73, 582, 439, 510]

TOPIC_SPECIFICITY_INSTRUCTION = (
    "O STEM (enunciado principal) deve nomear explicitamente o tópico/assunto "
    "específico deste item (ex: o autor, o conceito, o cenário concreto descrito "
    "no ITEM ORIGINAL acima) -- NÃO use um template genérico e reutilizável como "
    "'Ao analisar as asserções, assinale a alternativa correta.' ou 'Ao analisar "
    "o contexto apresentado, é correto APENAS o que se afirma em:'. Dois itens "
    "diferentes nunca devem compartilhar o mesmo stem genérico -- o stem deve, "
    "por si só, deixar claro do que trata ESTE item específico."
)


def log(msg: str) -> None:
    print(msg, flush=True)


async def regenerate_one(row: pd.Series, target_letter: str):
    question_id = int(row["question_id"])
    target_level, demoted = determine_target_level(row["taxonomy_level"], question_id=question_id)
    item_rng = random.Random(f"stemfix-{question_id}-{SEED}")
    fmt_feedback_extra = [TOPIC_SPECIFICITY_INSTRUCTION]
    feedback = list(fmt_feedback_extra)

    for attempt in range(1, MAX_RETRIES + 1):
        log(f"[{question_id}] attempt {attempt}: generating with topic-specificity instruction...")
        try:
            item, countdown_issues = await generator_agent(
                row, target_letter, target_level, demoted, GENERATOR_MODEL,
                feedback=feedback, item_rng=item_rng, target_word_count=None,
            )
        except Exception as exc:  # noqa: BLE001
            log(f"[{question_id}] attempt {attempt}: generator call failed: {exc}")
            feedback = fmt_feedback_extra + [f"Sua última resposta falhou: {exc}"]
            continue

        apply_position_shuffle(item, target_letter, item_rng)
        prefilter = run_mechanical_prefilter(item, target_letter, target_level, row["question_type"])
        if not prefilter.passed:
            log(f"[{question_id}] attempt {attempt}: REJECTED by mechanical pre-filter: "
                f"{'; '.join(prefilter.reasons)}")
            feedback = fmt_feedback_extra + list(prefilter.reasons) + countdown_issues
            continue

        outcome = await judge_agent(item, target_letter, target_level, JUDGE_MODEL, item_rng=item_rng)
        if outcome.approved:
            log(f"[{question_id}] attempt {attempt}: APPROVED. New stem: {item.stem!r}")
            return item, target_level, demoted, attempt
        log(f"[{question_id}] attempt {attempt}: REJECTED by judge: {'; '.join(outcome.reasons)}")
        feedback = fmt_feedback_extra + outcome.reasons

    log(f"[{question_id}] exhausted {MAX_RETRIES} attempts -- keeping prior content, flagging for review.")
    return None, None, None, MAX_RETRIES


async def main():
    df = pd.read_csv(CSV_PATH)
    assert len(df) == 100
    full_pool = build_candidate_pool(pool_size=None).set_index("question_id", drop=False)

    results = {}
    for qid in TARGET_QIDS:
        row = full_pool.loc[qid]
        target_letter = str(df.loc[df["question_id"] == qid, "correct_option"].iloc[0])
        item, target_level, demoted, attempts = await regenerate_one(row, target_letter)
        if item is not None:
            from WAPLA_AIG_Engine import ProcessedResult
            pr = ProcessedResult(question_id=qid, original_row=row.to_dict(),
                                  target_letter=target_letter, target_level=target_level,
                                  demoted=demoted, approved=True, attempts=attempts, final_item=item)
            new_row = item_to_row(pr)
            results[qid] = new_row
        else:
            results[qid] = None

    for qid, new_row in results.items():
        if new_row is None:
            continue
        idx = df.index[df["question_id"] == qid][0]
        for col, val in new_row.items():
            df.at[idx, col] = val

    df.to_csv(CSV_PATH, index=False, encoding="utf-8")
    log(f"Updated {CSV_PATH} in place for {sum(1 for v in results.values() if v)}/4 items.")
    for qid in TARGET_QIDS:
        log(f"  qid={qid}: {'UPDATED' if results[qid] else 'KEPT (exhausted, needs manual review)'}")


if __name__ == "__main__":
    asyncio.run(main())
